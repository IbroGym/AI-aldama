/**
 * Reads data/stop_translations.csv → lib/i18n/stop-translations-by-code.ts
 * Run: node tools/generate-stop-translations-ts.mjs
 */
import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, "..")
const csvPath = path.join(root, "data", "stop_translations.csv")
const outPath = path.join(root, "lib", "i18n", "stop-translations-by-code.ts")

function parseCsvLine(line) {
  const out = []
  let cur = ""
  let inQuotes = false
  for (let i = 0; i < line.length; i++) {
    const c = line[i]
    if (c === '"') {
      inQuotes = !inQuotes
      continue
    }
    if (c === "," && !inQuotes) {
      out.push(cur)
      cur = ""
      continue
    }
    cur += c
  }
  out.push(cur)
  return out
}

function esc(s) {
  return s.replace(/\\/g, "\\\\").replace(/'/g, "\\'")
}

const raw = fs.readFileSync(csvPath, "utf8").replace(/^\uFEFF/, "")
const lines = raw.split(/\r?\n/).filter(Boolean)
lines.shift()

const entries = []
for (const line of lines) {
  const [stop_code, , name_kk, name_ru, name_en] = parseCsvLine(line)
  if (!stop_code?.trim()) continue
  entries.push({
    stop_code: stop_code.trim(),
    name_kk: (name_kk ?? "").trim(),
    name_ru: (name_ru ?? "").trim(),
    name_en: (name_en ?? "").trim(),
  })
}

const body = entries
  .map(
    (e) =>
      `  "${e.stop_code}": { kk: '${esc(e.name_kk)}', ru: '${esc(e.name_ru)}', en: '${esc(e.name_en)}' },`
  )
  .join("\n")

const ts = `/** Auto-generated by tools/generate-stop-translations-ts.mjs — do not edit by hand. */
export type StopTranslationRow = { kk: string; ru: string; en: string }

export const STOP_TRANSLATIONS_BY_CODE: Record<string, StopTranslationRow> = {
${body}
}
`

fs.writeFileSync(outPath, ts, "utf8")
console.log(`Wrote ${entries.length} entries to ${outPath}`)
